import fs from 'node:fs';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell' });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, acceptDownloads: true });
const errs = []; page.on('pageerror', e => errs.push(e.message));
await page.goto('file:///home/claude/mcbs/dist/index.html');
await page.setInputFiles('#folder-input', '/tmp/claude-0/badworld');
await page.waitForTimeout(4000);
console.log('btn', await page.locator('#err-btn').textContent(), await page.locator('#err-btn').isVisible());
