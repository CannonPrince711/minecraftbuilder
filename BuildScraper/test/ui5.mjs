// Combined app: the 3D viewer tab, "View in 3D" from a world selection and from the convert list.
import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const errs = []; page.on('pageerror', e => errs.push(e.message)); page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto(process.argv[2] || 'file:///home/claude/mcbs/dist/index.html');
await page.click('#try-sample');
await page.waitForTimeout(4000);
const box = await page.locator('#map').boundingBox();
const cx = box.x + box.width / 2, cy = box.y + box.height / 2;
await page.mouse.move(cx - 60, cy - 60); await page.mouse.down(); await page.mouse.move(cx + 40, cy + 30, { steps: 5 }); await page.mouse.up();
await page.waitForTimeout(300);
await page.click('#preview');
const frame = () => page.frameLocator('#viewer-host iframe');
await frame().locator('#fileList li').first().waitFor({ timeout: 20000 });
await page.waitForTimeout(1500);
console.log('tab view visible', await page.locator('#pane-view').isVisible(), '| status:', await page.locator('#status').textContent());
console.log('viewer files:', await frame().locator('#fileList').innerText());
console.log('viewer info:', (await frame().locator('#info').innerText()).replace(/\n/g, ' | ').slice(0, 200));
await page.screenshot({ path: '/tmp/claude-0/v1.png' });
await page.click('#tab-convert');
await page.setInputFiles('#files-input', ['test/fixtures/viking-house1.schematic']);
await page.waitForTimeout(800);
await page.click('#conv-list [data-act="view"]');
await page.waitForTimeout(2500);
console.log('viewer files 2:', (await frame().locator('#fileList').innerText()).replace(/\n/g, ' | '));
await page.screenshot({ path: '/tmp/claude-0/v2.png' });
await page.setViewportSize({ width: 400, height: 800 });
await page.waitForTimeout(800);
await page.screenshot({ path: '/tmp/claude-0/v3.png' });
console.log('problems button:', await page.locator('#err-btn').isVisible() ? await page.locator('#err-btn').textContent() : 'none');
console.log('errors', errs);
await browser.close();
